"""Extract key Lean definitions (with bodies) and theorem statements (up to `:=`) into lean_statements.tex."""
import re, sys, hashlib, pathlib
src = pathlib.Path(sys.argv[1]).read_text()
names = ["RowSumLe", "CommonWeight", "IsTraj", "stepMap", "sech2", "rho", "absMat", "scalarMap", "linJ",
         "P1_global_bound", "P2_contraction", "weight_iff_rho_lt_one", "P3_K1_rate",
         "P4_rho_le_rho_abs", "P4_balanced_eq", "P5_diag_separable", "P6_gain", "P6_cooperative"]
out = []
for n in names:
    if n[0].isupper() and not n.startswith("P"):  # definitions: keep the body (up to the blank line)
        m = re.search(r"^(?:noncomputable )?def " + re.escape(n) + r"\b.*?(?=\n\s*\n)", src, re.S | re.M)
    elif n in ("stepMap", "sech2", "rho", "absMat", "scalarMap", "linJ"):
        m = re.search(r"^(?:noncomputable )?def " + re.escape(n) + r"\b.*?(?=\n\s*\n)", src, re.S | re.M)
    else:  # theorems: statement only, up to `:=`
        m = re.search(r"^(?:theorem|lemma) " + re.escape(n) + r"\b.*?:=", src, re.S | re.M)
    assert m, n
    t = m.group(0)
    out.append(t[:-2].rstrip() if t.endswith(":=") else t.rstrip())
body = "\n\n".join(out).replace("𝓝", "¦sym«𝓝»")  # glyph absent from DejaVu Sans Mono
h = hashlib.sha256(src.encode()).hexdigest()
pathlib.Path("lean_statements.tex").write_text(
    "% generated by gen_lean_appendix.py from KRippleV2.lean sha256 " + h + "\n"
    "\\begin{Verbatim}[fontsize=\\footnotesize,formatcom=\\leanfont,commandchars=¦«»]\n" + body + "\n\\end{Verbatim}\n")
print(h, len(body.splitlines()))
